import { assert, load } from './runtime.mjs';
const m = await load('web/index.ts');
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
const store = m.createPreferences(storage);
assert.equal(store.get('sound'), true);
const events = [];
const off = store.subscribe((key, value) => events.push([key, value]));
store.set('sound', false);
store.set('language', 'fr');
assert.equal(m.createPreferences(storage).get('sound'), false);
assert.deepEqual(events, [['sound', false], ['language', 'fr']]);
off();
store.set('sound', true);
assert.equal(events.length, 2);
const encoded = m.exportAll(storage);
store.reset();
assert.equal(store.get('language'), null);
assert.equal(m.importAll(storage, encoded).imported, 2);
assert.equal(store.get('language'), 'fr');
assert.equal(m.availableDeviceId('gone', ['available']), '');
